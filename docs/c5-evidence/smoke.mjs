/**
 * C5 clean-install smoke test — the packaged @victframework/cognee tarball,
 * installed into a THROWAWAY project together with the supported VICT
 * packages, exercised through a REAL VICT runtime on a disposable store.
 *
 * Run with plain node (NO tsx, NO repo-relative paths, NO build tooling):
 *   node smoke.mjs
 *
 * Proves:
 *  S1  the installed package validates against the VICT SDK (manifest);
 *  S2  the installed package resolves its OWN bundled worker + guard inside
 *      node_modules (no repo-relative path);
 *  S3  a durable keyed write graph (add + cognify) completes through the
 *      REAL worker on a disposable store (receipts contract-conform);
 *  S4  a scoped search through the runtime returns the marker (in-scope);
 *  S5  exclusive store ownership: the lock lives in the store, is released
 *      on shutdown; a second pack instance on the same store refuses;
 *  S6  the shipped worker carries no fault-injection hook.
 */

import { mkdirSync, rmSync, writeFileSync, existsSync, readFileSync, unlinkSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

const { validateCapabilityPack, neutralJsonContract } = await import('@victframework/sdk');
const { createRuntime, createInMemoryStores, installCapabilityPack } =
  await import('@victframework/runtime');
const { createCogneePack, WorkerError } = await import('@victframework/cognee');

// ---- tested Python provisioning (absolute path; see README) ------------------
const PY = 'C:/Users/RZ1/Desktop/RZ/260925-VCT-Cognee/proof/.venv/Scripts/python.exe';

// ---- fresh disposable store INSIDE the throwaway project ---------------------
const STORE = path.join(here, '.smoke-store');
for (let attempt = 0; ; attempt++) {
  try { rmSync(STORE, { recursive: true, force: true }); break; }
  catch { if (attempt >= 4) throw new Error('cannot clear store'); await new Promise((r) => setTimeout(r, 1_000)); }
}
mkdirSync(path.join(STORE, 'system'), { recursive: true });
writeFileSync(path.join(STORE, '.env'), [
  '# C5 smoke disposable store (generated by smoke.mjs — safe to delete)',
  'ENV=dev', 'RUNTIME__LOG_LEVEL=INFO',
  ...Object.entries({
    SYSTEM_ROOT_DIRECTORY: 'system', DATA_ROOT_DIRECTORY: 'data',
    CACHE_ROOT_DIRECTORY: 'cache', LOGS_ROOT_DIRECTORY: 'logs',
    COGNEE_REPOS_DIR: 'repos',
  }).map(([k, v]) => `${k}=${path.join(STORE, v).replace(/\\/g, '/')}`),
  'VECTOR_DB_PROVIDER=lancedb', 'GRAPH_DATABASE_PROVIDER=ladybug',
  'DB_PROVIDER=sqlite', 'EMBEDDING_PROVIDER=fastembed',
  'EMBEDDING_MODEL=BAAI/bge-small-en-v1.5', 'EMBEDDING_DIMENSIONS=384',
  'GRAPH_EXTRACTOR=gliner_demo', 'AUTO_FEEDBACK=false', '',
].join('\n'));

const results = [];
const check = (id, name, cond, detail) => {
  results.push({ id, name, outcome: cond ? 'PASS' : 'FAIL', detail });
  console.error(`[smoke] ${id} ${cond ? 'PASS' : 'FAIL'} ${name}`);
  if (!cond && detail !== undefined) {
    console.error(`[smoke] ${id} detail: ${JSON.stringify(detail)?.slice(0, 600)}`);
  }
  return cond;
};

// ---- the pack, from the INSTALLED package ------------------------------------
const pack = createCogneePack({
  pythonPath: PY, cwd: STORE, storeRoot: STORE, namespaces: ['qa'],
  readyBudgetMs: 180_000,
  diag: (line) => console.error(`[smoke-sup] ${line.slice(0, 140)}`),
});

// ---- runtime glue (pure capabilities + contracts only) -----------------------
const neutralContract = {
  id: 'smoke.neutral', revision: '1', expected: 'any object',
  parse: (input) => typeof input === 'object' && input !== null
    ? { ok: true, value: input }
    : { ok: false, issues: [{ code: 'SHAPE', path: '$', message: 'expected object' }] },
};
const routeContract = {
  id: 'smoke.route-result', revision: '1', expected: '{ route, value }',
  parse: (input) => {
    const o = input;
    if (o && typeof o === 'object' && typeof o.route === 'string' && typeof o.value === 'object')
      return { ok: true, value: o };
    return { ok: false, issues: [{ code: 'SHAPE', path: '$', message: 'expected { route, value }' }] };
  },
};
const routeCapability = {
  id: 'smoke.route', revision: '1', effect: 'pure', input: neutralContract, output: routeContract,
  invoke: (input) => ({ route: 'go', value: input }),
};
const identityCapability = {
  id: 'smoke.identity', revision: '1', effect: 'pure',
  input: neutralJsonContract, output: neutralJsonContract,
  invoke: (input) => input,
};
const searchShapeCapability = {
  id: 'smoke.search-shape', revision: '1', effect: 'pure',
  input: neutralJsonContract, output: neutralJsonContract,
  invoke: (input) => ({ datasets: [input.datasetName], query: input.query, topK: 5 }),
};

const WRITE_GRAPH = {
  id: 'c5-smoke-write', entry: 'decide',
  nodes: [
    { id: 'decide', kind: 'decision', capability: 'smoke.route' },
    { id: 'put', capability: 'cognee.add',
      retry: { maxAttempts: 2, retryOn: ['VICT_RUNTIME_CAPABILITY_THREW'],
        backoff: { kind: 'fixed', delayMs: 200 } },
      timeoutMs: 180_000, output: 'cognee.mutating-receipt' },
    { id: 'adapt', capability: 'smoke.identity' },
    { id: 'graph', capability: 'cognee.cognify',
      retry: { maxAttempts: 2, retryOn: ['VICT_RUNTIME_CAPABILITY_THREW'],
        backoff: { kind: 'fixed', delayMs: 200 } },
      timeoutMs: 300_000, output: 'cognee.mutating-receipt' },
  ],
  edges: [
    { from: 'decide', to: 'put', kind: 'route', key: 'go' },
    { from: 'put', to: 'adapt' },
    { from: 'adapt', to: 'graph' },
  ],
};
const READ_GRAPH = {
  id: 'c5-smoke-read', entry: 'find',
  nodes: [
    // capability-only graph (no retry/timeout/decision) — the graph input IS
    // the search input (mirrors verify.ts V5's read graph).
    { id: 'find', capability: 'cognee.searchChunks', output: 'cognee.search-output' },
  ],
  edges: [],
};

// ---- S1: manifest validates via the installed SDK -----------------------------
{
  const validation = validateCapabilityPack(pack, { victVersion: '0.1.0' });
  check('S1', 'installed pack manifest validates against @victframework/sdk', validation.ok === true,
    validation.ok ? { capabilities: pack.manifest.capabilities.length } : validation.issues);
}

// ---- S2: bundled worker resolves INSIDE node_modules --------------------------
{
  const wp = pack.supervision.workerPath.replace(/\\/g, '/');
  const nm = path.join(here, 'node_modules').replace(/\\/g, '/');
  check('S2', 'bundled worker + guard resolve inside node_modules/@victframework/cognee/dist (no repo-relative path)',
    wp.startsWith(nm) && wp.endsWith('dist/worker/cognee_worker.py') &&
      existsSync(wp) && existsSync(wp.replace('cognee_worker.py', 'guard_store_roots.py')),
    { workerPath: wp });
}

// ---- runtime + install ---------------------------------------------------------
const runtime = createRuntime({
  stores: createInMemoryStores(),
  authority: { grants: ['cognee.write', 'cognee.search', 'cognee.delete'] },
});
runtime.registerContract(neutralContract).registerContract(routeContract)
  .registerContract(neutralJsonContract);
runtime.registerCapability(routeCapability).registerCapability(identityCapability)
  .registerCapability(searchShapeCapability);
const { installed } = installCapabilityPack(runtime, pack);
if (installed.length !== 6) {
  check('S2b', 'all six capabilities installed', false, { installed: [...installed] });
}

// ---- S3: durable keyed write graph (add + cognify) through the REAL worker -----
const DOC = 'C5 smoke marker: settlement windows close at 17:00 local time; ledger ' +
  'reconciliation runs nightly under dual approval.';
{
  const activated = await runtime.activate(WRITE_GRAPH);
  if (!activated.ok) {
    check('S3', 'keyed write graph completes through the real worker', false,
      { issues: activated.issues.map((i) => i.code) });
  } else {
    const run = await runtime.run({ datasetName: 'qa.smoke', content: DOC }, { mode: 'normal' });
    const receipt = run.output ?? {};
    check('S3', 'keyed write graph (add + cognify) completes through the real worker (contract-conform receipts)',
      run.status === 'completed' && receipt.datasetName === 'qa.smoke' &&
        typeof receipt.idempotencyKey === 'string' && receipt.reconciled === 'fresh-execution',
      { status: run.status, output: receipt, error: run.error ?? null,
        spawns: pack.supervision.stats.spawns });
  }
}

// ---- S4: scoped search through the runtime --------------------------------------
{
  const activated = await runtime.activate(READ_GRAPH);
  if (!activated.ok) {
    check('S4', 'scoped search returns the marker', false,
      { issues: activated.issues.map((i) => i.code) });
  } else {
    const run = await runtime.run(
      { datasets: ['qa.smoke'], query: 'settlement windows' }, { mode: 'normal' });
    const search = run.output ?? {};
    check('S4', 'scoped search through the runtime returns the marker (in-scope)',
      run.status === 'completed' && (search.total ?? 0) > 0 &&
        search.hits?.[0]?.datasetName === 'qa.smoke' &&
        String(search.hits?.[0]?.text ?? '').includes('C5 smoke marker'),
      { status: run.status, total: search.total, first: search.hits?.[0] });
  }
}

// ---- S5: exclusive store ownership in the installed package ---------------------
{
  const LOCK = path.join(STORE, 'cognee-store-owner.lock');
  const held = pack.supervision.storeOwnershipHeld && existsSync(LOCK);
  let refused = null;
  try {
    createCogneePack({
      pythonPath: PY, cwd: STORE, storeRoot: STORE, namespaces: ['qa'],
      diag: () => {},
    });
  } catch (e) { refused = e; }
  check('S5', 'second instance on the same store refuses (COGNEE_STORE_OWNED, pre-spawn)',
    held && refused instanceof WorkerError && refused.code === 'COGNEE_STORE_OWNED' &&
      pack.supervision.stats.spawns === 1,
    { held, refused: refused instanceof Error ? refused.code ?? refused.name : String(refused) });
  await pack.supervision.shutdown();
  check('S5', 'orderly shutdown releases ownership (lock gone)',
    !pack.supervision.storeOwnershipHeld && !existsSync(LOCK), {});
}

// ---- S6: shipped worker carries no fault-injection hook --------------------------
{
  const wp = pack.supervision.workerPath;
  const worker = readFileSync(wp, 'utf8');
  const guard = readFileSync(wp.replace('cognee_worker.py', 'guard_store_roots.py'), 'utf8');
  check('S6', 'shipped worker + guard contain no test fault hook (C4_PROOF_FAULT absent)',
    !worker.includes('C4_PROOF_FAULT') && !guard.includes('C4_PROOF_FAULT') &&
      !worker.includes('STUB_'),
    {});
}

console.error(`[smoke] COMPLETE — ${results.filter((r) => r.outcome === 'PASS').length}/${results.length} PASS`);
process.exit(results.some((r) => r.outcome !== 'PASS') ? 1 : 0);
