/**
 * C4 proof driver — corrected worker boundary vs corrected pack contract.
 *
 * Tests the C4 corrections on top of the C3 contract (fresh disposable store
 * proof/.cognee-c4, own .env + journal, guard boundary = that store):
 *  - retry key EXCLUSIVITY: mutating ops take the key ONLY from the request
 *    `ctx` (VICT CapabilityContext.idempotencyKey); a key in op params is
 *    rejected; a mutation without any ctx key is rejected;
 *  - journal keys are BOUND to (op, dataset, input fingerprint); mismatched
 *    reuse is rejected with COGNEE_IDEMPOTENCY_MISMATCH, journal unchanged;
 *  - FORCED CRASH AFTER Cognee's write but BEFORE the journal commit
 *    (PROOF-ONLY harness worker/worker_proof.py, env C4_PROOF_FAULT — the
 *    pack-bundled worker itself ships NO fault injection): the client reports
 *    COGNEE_WRITE_UNKNOWN (any worker exit during a pending mutation), the
 *    keyed reissue re-executes convergently — item-level convergence for add
 *    (count stays 1, no duplicate) and graph-level convergence for cognify
 *    (dataset searchable after reissue);
 *  - regressions: scope rails, scoped datasetsStatus (seeded foreign
 *    datasets), bounds, summary isolation both sides, forget receipt.
 * Results: worker/c4-results.json; diagnostics: worker/c4.log (stderr).
 */

