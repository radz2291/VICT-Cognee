await scenario('c5', 'forced crash AFTER add write, BEFORE journal commit', async () => {
  // ONE worker per store: park the main worker before arming the crash worker.
  await client.shutdown();
  const cc = crashClient('add.after-write-before-commit');
  const t = Date.now();
  try {
    await cc.ensureReady();
    await cc.request('add', { datasetName: 'qa.crashadd', content: crashDoc },
      { mutating: true, deadlineMs: 180_000, ctx: { idempotencyKey: 'k5' } });
    record('c5', 'crash hook did not fire (add completed)', 'FAIL-UNEXPECTED', {},
      Date.now() - t);
    return;
  } catch (e) {
    if (e.code !== 'COGNEE_WRITE_UNKNOWN') throw e;
    record('c5', 'worker exit during pending add -> COGNEE_WRITE_UNKNOWN',
      e.detail?.workerExit?.code === 2 ? 'PASS' : 'FAIL',
      { idempotencyKey: 'k5', workerExit: e.detail?.workerExit }, Date.now() - t);
  }
  // journal now holds exactly the crash evidence: begun WITHOUT completed
  const afterCrash = journalRecords().filter((r) => r.key === 'k5');
  record('c5', 'journal shows begun-without-commit after the forced crash',
    afterCrash.length === 1 && afterCrash[0].state === 'begun' ? 'PASS' : 'FAIL',
    { records: afterCrash.map((r) => r.state) });
  const t2 = Date.now();
  const re1 = await client.request('add', { datasetName: 'qa.crashadd',
    content: crashDoc }, { mutating: true, deadlineMs: 180_000,
    ctx: { idempotencyKey: 'k5' } });
  record('c5', 'reissue after crash-before-commit re-executes convergently',
    re1.reconciled === 'reissued-after-interruption' && re1.itemsAfter === 1
      ? 'PASS' : 'FAIL', // item-level convergence: landed write + re-exec = 1 item
    re1, Date.now() - t2);
  const t3 = Date.now();
  const re2 = await client.request('add', { datasetName: 'qa.crashadd',
    content: crashDoc }, { mutating: true, ctx: { idempotencyKey: 'k5' } });
  record('c5', 'post-reissue same key replays known outcome',
    re2.reconciled === 'replayed-known-outcome' && re2.itemsAfter === 1
      ? 'PASS' : 'FAIL', re2, Date.now() - t3);
});

await scenario('c6', 'forced crash AFTER cognify write, BEFORE commit', async () => {
  const t = Date.now();
  await client.request('add', { datasetName: 'qa.cognicrash', content: crashDoc },
    { mutating: true, deadlineMs: 120_000, ctx: { idempotencyKey: 'k6a' } });
  // ONE worker per store: park the main worker before arming the crash worker.
  // A cognee-internal cognify failure (flaky class) leaves begun-without-commit
  // in the journal — the retry below re-arms the hook and re-executes the SAME
  // key, which the journal reconciles exactly like a real interruption.
  for (let attempt = 1; attempt <= 2; attempt++) {
    await client.shutdown();
    const cc = crashClient('cognify.after-write-before-commit');
    try {
      await cc.ensureReady();
      await cc.request('cognify', { datasetName: 'qa.cognicrash' },
        { mutating: true, deadlineMs: 240_000, ctx: { idempotencyKey: 'k6' } });
      record('c6', `cognify crash hook did not fire (attempt ${attempt})`,
        'FAIL-UNEXPECTED', {}, Date.now() - t);
      return;
    } catch (e) {
      if (e.code === 'COGNEE_WRITE_UNKNOWN' &&
          e.detail?.workerExit?.code === 2) {
        record('c6', 'worker exit during pending cognify -> COGNEE_WRITE_UNKNOWN',
          'PASS', { idempotencyKey: 'k6', workerExit: e.detail?.workerExit,
            attempt }, Date.now() - t);
        break;
      }
      if (attempt === 2 || e.code !== 'COGNEE_ERROR') throw e;
      record('c6', `cognify failed internally before the hook (attempt ${attempt}); retrying`,
        'AGENT-OBSERVATION', { code: e.code,
          message: String(e.message).slice(0, 120) });
    }
  }
  const afterCrash = journalRecords().filter((r) => r.key === 'k6');
  record('c6', 'journal shows begun-without-commit after the forced cognify crash',
    afterCrash.length >= 1 &&
      afterCrash[afterCrash.length - 1].state === 'begun' ? 'PASS' : 'FAIL',
    { records: afterCrash.map((r) => r.state) });
  const t2 = Date.now();
  const con = await client.request('cognify', { datasetName: 'qa.cognicrash' },
    { mutating: true, deadlineMs: 240_000, ctx: { idempotencyKey: 'k6' } });
  const search = await client.request('search_chunks',
    { datasets: ['qa.cognicrash'], query: 'C4CRASH', topK: 3 });
  record('c6', 'cognify reissue converges (graph searchable after interruption)',
    con.reconciled === 'reissued-after-interruption' && search.total > 0
      ? 'PASS' : 'FAIL',
    { reconciled: con.reconciled, itemsAfter: con.itemsAfter,
      searchTotal: search.total }, Date.now() - t2);
});

