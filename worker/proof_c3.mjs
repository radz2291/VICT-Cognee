/**
 * C3 proof driver v2 — hardened worker vs corrected pack contract, FRESH store.
 *
 * Corrections tested here (docs/c3-pack-contract.md correction pass):
 *  - one worker / one store / one trust domain: every run gets a FRESH
 *    disposable store (proof/.cognee-c3) built from its own .env;
 *  - datasetsStatus is scope-filtered: pre-existing datasets OUTSIDE the
 *    permitted domain (seeded first: legacy_unscoped, outside.vault) are
 *    never revealed, and addressing them is rejected;
 *  - durable keyed reconciliation with the VICT idempotencyKey for add and
 *    cognify: replay known outcomes, re-execute after interruption with
 *    item-level counts, dedupe convergence; forgetDataset has no journal and
 *    no auto-retry;
 *  - summary isolation with BOTH sides populated.
 * Worker death with a pending mutation stays an unknown outcome
 * (COGNEE_WRITE_UNKNOWN + poison + respawn); crashes are AGENT-OBSERVATIONs.
 * Results: worker/c3-results.json; diagnostics: worker/c3.log (stderr).
 */

